public class TiposPrimitivos {
    public static void main(String[] args){
        byte num = 1;
        short num2 = 327; //geralmente números mais curtos
        int num3 = 500; //o mais usado
        long num4 = 200000000L; //geralmente números maiores, quando declaramos uma variável como long, colocamos L no final do número, ou seja 200000000L, dessa forma deixamos claro que é long quando declaramos var ao invés de tipar
        float num5 = 1.0f; //usado para números decimais, e tem que tipar com f no final para a mesma finalidade do long (e para diferenciar do double)
        double num6 = 2.0d; //usado para números decimais, e tem que tipar pela mesma finalidade do float
        char caractere = 'a'; //usado para caracteres e lembre que no char se usa aspas simples para diferenciar da String
        boolean verdadeiro = true;
    }
}
